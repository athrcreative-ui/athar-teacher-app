export function getLessonAssistantGuide(lessonId: string, lesson?: LessonContent): LessonAssistantGuide | null {
  const customGuide = assistantGuides[lessonId];
  if (customGuide) {
    return customGuide;
  }

  const meta = lessonMetaMap[lessonId];
  if (!meta) {
    return null;
  }

  return generateUniversalGuide(meta, lesson);
}

